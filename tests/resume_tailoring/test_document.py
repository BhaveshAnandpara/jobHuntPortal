def reopen(content: bytes) -> Document:
    """Re-open generated bytes as a document — the round trip under test."""
    return Document(io.BytesIO(content))


def external_link_targets(document: Document) -> list[str]:
    """Every external hyperlink relationship the document actually declares.

    Read from the package's relationship part, not from the paragraph text —
    a label rendered without a working relationship is exactly the failure
    these tests exist to catch.
    """
    return [
        relationship.target_ref
        for relationship in document.part.rels.values()
        if relationship.reltype == RELATIONSHIP_TYPE.HYPERLINK
        and relationship.is_external
    ]


def hyperlink_labels(document: Document) -> list[str]:
    """The visible text of each `w:hyperlink` element, in document order."""
    labels = []
    for paragraph in document.paragraphs:
        for hyperlink in paragraph._p.findall(qn("w:hyperlink")):
            labels.append(
                "".join(node.text or "" for node in hyperlink.iter(qn("w:t")))
            )
    return labels


def runs_of(document: Document, predicate) -> list:
    for paragraph in document.paragraphs:
        if predicate(paragraph.text):
            return list(paragraph.runs)
    raise AssertionError("no paragraph matched")


def _pattern_for(skills: list[str]):
    """The emphasis pattern the renderer builds for a given skills list.

    Reaching for the private builder here is deliberate: these two tests are
    about the *matching rule* (whole words, longest first), which is far
    easier to state on the pure function than to infer from bold runs.
    """
    from resume_tailoring.document import _skill_pattern

    return _skill_pattern(skills)


def bottom_border(paragraph) -> object | None:
    ppr = paragraph._p.pPr
    if ppr is None:
        return None
    borders = ppr.find(qn("w:pBdr"))
    return None if borders is None else borders.find(qn("w:bottom"))


def paragraph_texts(document: Document) -> list[str]:
    return [paragraph.text for paragraph in document.paragraphs]


def all_text(document: Document) -> str:
    return "\n".join(paragraph_texts(document))


