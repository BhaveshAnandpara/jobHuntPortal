@pytest.mark.parametrize(
    "section", [SECTION_SUMMARY, SECTION_EXPERIENCE, SECTION_EDUCATION]
)
def test_section_headings_are_bold_accent_and_display_uppercase(
    rendered: Document, section: str
) -> None:
    paragraph = next(p for p in rendered.paragraphs if p.text == section)

    assert paragraph.runs
    for run in paragraph.runs:
        assert run.bold is True
        assert run.font.color.rgb == ACCENT_COLOR
        assert run.font.name == FONT_NAME
        # `w:caps` uppercases only the rendering — the text a parser reads
        # stays the ordinary section name.
