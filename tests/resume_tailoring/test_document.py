def test_a_bullet_with_no_skill_term_stays_entirely_plain(rendered: Document) -> None:
    """The fixture's first bullet says "ventilatory", not "ventilator", so
    the whole-word rule must leave it alone — a near-miss must not bold."""
    runs = runs_of(rendered, lambda text: text.startswith("Cared for post-operative"))

    assert [run.text for run in runs if run.bold] == []
    assert "".join(run.text for run in runs) == (
        "Cared for post-operative patients requiring ventilatory support"
    )


def test_bolding_marks_the_matching_term_and_nothing_else() -> None:
    profile = make_profile(
        skills=["Ventilator management", "Sepsis"],
        work_history=[
            WorkExperienceEntry(
                company="St Bede's Trust",
                title="Staff Nurse",
                start_date="Aug 2019",
                bullets=["Led ventilator management drills after every sepsis alert"],
            )
        ],
    )
    document = reopen(build_resume_document(profile))

    runs = runs_of(document, lambda text: text.startswith("Led "))

    assert [run.text for run in runs if run.bold] == [
        "ventilator management",
        "sepsis",
    ]
    assert [run.text for run in runs if not run.bold] == [
        "Led ",
        " drills after every ",
        " alert",
    ]
    for run in runs:
        assert run.font.color.rgb == INK_COLOR
        assert run.font.name == FONT_NAME


def test_bolding_never_changes_a_single_character_of_the_bullet() -> None:
    """The emphasis pass is presentational: the runs must concatenate back
    to exactly the text the tailoring step produced."""
    bullet = "Led ventilator management drills after every sepsis alert"
    profile = make_profile(
        skills=["Ventilator management", "Sepsis", "Drills"],
        work_history=[
            WorkExperienceEntry(
                company="St Bede's Trust",
                title="Staff Nurse",
                start_date="Aug 2019",
                bullets=[bullet],
            )
        ],
    )

    texts = paragraph_texts(reopen(build_resume_document(profile)))

    assert bullet in texts


def test_bolding_matches_whole_words_only() -> None:
    """A skill must not be bolded where it is merely a fragment of a longer
    word — "care" inside "careful" is not the skill."""
    segments = emphasis_segments(
        "Was careful with care planning", _pattern_for(["care"])
    )

    assert segments == [("Was careful with ", False), ("care", True), (" planning", False)]


def test_bolding_prefers_the_longest_matching_skill() -> None:
    segments = emphasis_segments(
        "Ran critical care nursing handovers",
        _pattern_for(["Nursing", "Critical care nursing"]),
    )

    assert ("critical care nursing", True) in segments


